"""Generated graph skills of a modular graph (plan decision M7): the ``modules`` block, one
page per module, ``references/model.md`` as an index; the single-module fixtures stay as
they are (their goldens are covered by ``test_graph_skill_render``)."""

import re

import pytest
from support.fixtures import FIXTURES, GOLDENS, TOY_ONTOLOGIES, assert_golden, compiled_model
from support.skills import GRAPH_SKILL_NAME, render_inputs

from graph_cli.skills.graph_skill import render_checked, render_graph_skill
from graph_cli.skills.template import BLOCKS, MODEL_FILE, MODULES_DIR, parse_template
from graph_cli.skills.tree import MAX_SKILL_LINES, SKILL_FILE, read_tree

COMPANY_TEMPLATE = FIXTURES / "skills" / "company" / GRAPH_SKILL_NAME
BLOCKS_TEMPLATE = FIXTURES / "skills" / "blocks" / GRAPH_SKILL_NAME
VERSIONS = ("1.0.0", "1.1.0")
PAGES_1_1 = [f"{MODULES_DIR}{m}.md" for m in ("company", "operations", "organization", "people")]


def template_files() -> dict[str, bytes]:
    files, problems = read_tree(COMPANY_TEMPLATE)
    assert problems == []
    return files


def render(
    ontology: str = "company",
    version: str | None = None,
    files: dict[str, bytes] | None = None,
) -> dict[str, bytes]:
    documents, graph = render_inputs(compiled_model(ontology, version))
    rendered, problems = render_checked(
        files or template_files(), documents, graph, name=GRAPH_SKILL_NAME
    )
    assert problems == [] and rendered is not None
    return rendered


def text(files: dict[str, bytes], path: str) -> str:
    return files[path].decode()


@pytest.mark.parametrize("version", VERSIONS)
def test_goldens(version: str) -> None:
    files = render(version=version)
    for name, data in files.items():
        assert_golden(GOLDENS / "skills" / "company" / version / name, data)


def test_modules_is_a_known_block_once() -> None:
    assert BLOCKS.count("modules") == 1
    template, problems = parse_template(template_files())
    assert problems == [] and template is not None
    assert [name for _, name in template.blocks] == ["start", "modules", "names", "model"]


def test_the_block_is_a_compact_table_and_a_pointer() -> None:
    skill = text(render(version="1.1.0"), SKILL_FILE)
    rows = [line for line in skill.splitlines() if re.match(r"^\| `(company|ops|org|ppl)?", line)]
    assert [row.split("|")[1].strip() for row in rows] == [
        "`company`",
        "`operations`",
        "`organization`",
        "`people`",
    ]
    org = next(row for row in rows if row.startswith("| `organization`"))
    assert "| `org` |" in org and "| 5 |" in org
    assert "`operations` (0 out, 2 in), `people` (0 out, 1 in)" in org
    assert "Built-in modules, shared by every graph: `core`." in skill
    assert "`core` |" not in skill  # no row for a built-in module
    for command in (
        "graph describe module <module> --graph example_graph --json",
        "graph describe search <text> --graph example_graph --json",
        "graph describe type <type> --graph example_graph --json",
    ):
        assert command in skill
    assert "| Type |" not in skill and "| Relation |" not in skill  # no types/relations blocks


def test_a_module_page_lists_types_relations_links_and_rules() -> None:
    files = render(version="1.1.0")
    page = text(files, f"{MODULES_DIR}organization.md")
    assert page.startswith("<!-- Generated by graph_cli.skills for graph example_graph")
    assert "# Module `organization` of graph `example_graph`" in page
    assert "| `org:OrgUnit` |  | yes |  |" in page  # abstract, no alias
    assert "| `org:Team` | `TEAM-0001` | no | `org:OrgUnit` |" in page
    assert "| `org:in_unit` | `org:Position` | `org:OrgUnit` | out 1..1 |" in page
    out = page.split("## Links from other modules")[0].split("## Links to other modules")[1]
    assert "None." in out
    links_in = page.split("## Links from other modules")[1].split("## Rules")[0]
    assert "| `org:holds` | `ppl:Person` | `org:Position` | `people` |" in links_in
    assert "| `ops:owned_by` | `ops:Process` | `org:Position` | `operations` |" in links_in
    assert "`org.team_in_department` | error |" in page
    people = text(files, f"{MODULES_DIR}people.md")
    assert "| `org:holds` | `ppl:Person` | `org:Position` | `organization` |" in people
    assert "| `ops:" in people and "`operations`" in people
    umbrella = text(files, f"{MODULES_DIR}company.md")
    assert umbrella.count("None.") == 5  # holds no terms of its own


def test_model_md_is_an_index_of_modules_and_types() -> None:
    files = render(version="1.1.0")
    index = text(files, MODEL_FILE)
    for module in ("company", "operations", "organization", "people"):
        assert f"[{module}.md](modules/{module}.md)" in index
    assert "| `core` | `core` |  |" in index  # built in: no page
    model = compiled_model("company", "1.1.0")
    for curie in model.classes:
        assert re.search(rf"^\| `{curie}` \| `\w+` \| \[\w+\.md\]", index, re.MULTILINE), curie
    assert "## `" not in index  # no per-type sections
    assert "Fields:" not in index
    assert f"[{MODEL_FILE}]({MODEL_FILE})" in text(files, SKILL_FILE)


def test_the_files_of_a_modular_skill() -> None:
    assert sorted(render(version="1.1.0")) == sorted([SKILL_FILE, MODEL_FILE, *PAGES_1_1])
    assert f"{MODULES_DIR}operations.md" not in render(version="1.0.0")


def test_the_published_skill_md_stays_small() -> None:
    for version in VERSIONS:
        lines = text(render(version=version), SKILL_FILE).count("\n")
        assert lines < MAX_SKILL_LINES // 4


def test_a_new_pin_changes_every_modular_file_set() -> None:
    old, new = render(version="1.0.0"), render(version="1.1.0")
    assert old[SKILL_FILE] != new[SKILL_FILE] and old[MODEL_FILE] != new[MODEL_FILE]
    assert old[f"{MODULES_DIR}organization.md"] != new[f"{MODULES_DIR}organization.md"]
    assert render(version="1.1.0") == new  # same input, same bytes


def test_a_curated_file_below_the_modules_directory_is_refused() -> None:
    for path in (f"{MODULES_DIR}organization.md", f"{MODULES_DIR}notes.md"):
        files = {**template_files(), path: b"# Mine\n"}
        _, problems = parse_template(files)
        assert [(p.rule, p.path) for p in problems] == [("template", path)]
        assert "generated from the model; remove this file" in problems[0].message
    documents, graph = render_inputs(compiled_model("company", "1.1.0"))
    files = {**template_files(), MODEL_FILE: b"# Mine\n"}
    rendered, problems = render_checked(files, documents, graph, name=GRAPH_SKILL_NAME)
    assert rendered is None and [p.path for p in problems] == [MODEL_FILE]


@pytest.mark.parametrize("ontology", TOY_ONTOLOGIES)
def test_a_single_module_graph_gets_no_pages(ontology: str) -> None:
    """The renderer ignores the module documents unless the graph is modular."""
    files = render(ontology, files=read_tree(BLOCKS_TEMPLATE)[0])
    assert sorted(files) == [SKILL_FILE, MODEL_FILE]
    assert "## `" in text(files, MODEL_FILE)  # the full model, not an index


@pytest.mark.parametrize("ontology", TOY_ONTOLOGIES)
def test_the_block_on_a_single_module_graph_has_no_page_pointers(ontology: str) -> None:
    files = read_tree(BLOCKS_TEMPLATE)[0]
    skill = (
        files[SKILL_FILE]
        .decode()
        .replace("<!-- graph_cli:block start -->", "<!-- graph_cli:block modules -->")
    )
    documents, graph = render_inputs(compiled_model(ontology))
    template, _ = parse_template({**files, SKILL_FILE: skill.encode()})
    assert template is not None
    rendered = render_graph_skill(template, documents, graph)
    assert "graph describe module <module>" in rendered[SKILL_FILE]
    assert MODULES_DIR not in rendered[SKILL_FILE]
