"""Generated graph skills: goldens, determinism, completeness and size (Q2, Q6, Q10).

The goldens render the blocks fixture (every block once) for both toy ontologies.
The completeness check is built from the compiled model directly, not from the
renderer or the describe documents (research 06, test_p27 pattern).
"""

import re
from typing import Any

import pytest
from support.fixtures import FIXTURES, GOLDENS, TOY_ONTOLOGIES, assert_golden, compiled_model
from support.skills import GRAPH_SKILL_NAME, graph_entry, render_inputs

from graph_cli.kernel.ids import format_alias
from graph_cli.ontology_layer.model import CompiledModel
from graph_cli.skills.graph_skill import render_checked, render_graph_skill
from graph_cli.skills.template import MODEL_FILE, parse_template
from graph_cli.skills.tree import MAX_SKILL_LINES, SKILL_FILE, read_tree

BLOCKS_TEMPLATE = FIXTURES / "skills" / "blocks" / GRAPH_SKILL_NAME


def template_files() -> dict[str, bytes]:
    files, problems = read_tree(BLOCKS_TEMPLATE)
    assert problems == []
    return files


def render(model: CompiledModel, **kw: Any) -> dict[str, bytes]:
    documents, graph = render_inputs(model, **kw)
    files, problems = render_checked(template_files(), documents, graph, name=GRAPH_SKILL_NAME)
    assert problems == [] and files is not None
    return files


@pytest.mark.parametrize("ontology", TOY_ONTOLOGIES)
def test_goldens(ontology: str) -> None:
    files = render(compiled_model(ontology))
    assert sorted(files) == [SKILL_FILE, MODEL_FILE]
    for name, data in files.items():
        assert_golden(GOLDENS / "skills" / ontology / name, data)


@pytest.mark.parametrize("ontology", TOY_ONTOLOGIES)
def test_same_input_same_bytes(ontology: str) -> None:
    model = compiled_model(ontology)
    assert render(model) == render(model)


def test_curated_text_and_extra_files_are_kept() -> None:
    files = template_files()
    files["references/recipes.md"] = b"# Recipes\n"
    documents, graph = render_inputs(compiled_model("inventory"))
    rendered, problems = render_checked(files, documents, graph, name=GRAPH_SKILL_NAME)
    assert problems == [] and rendered is not None
    assert rendered["references/recipes.md"] == b"# Recipes\n"
    text = rendered[SKILL_FILE].decode()
    assert text.startswith(files[SKILL_FILE].decode().split("\n\n")[0])  # frontmatter as is
    assert "## Is it available here?" in text and "graph_cli:block" not in text


def test_stamp_names_graph_release_and_template_only() -> None:
    model = compiled_model("inventory")
    text = render(model)[SKILL_FILE].decode()
    (stamp,) = re.findall(r"<!-- Generated by .*? -->", text)
    assert "example_graph" in stamp and f"{model.bundle_id} {model.bundle_version}" in stamp
    assert re.search(r"sha256:[0-9a-f]{64}", stamp)
    assert "0.1" not in stamp and not re.search(r"\d{4}-\d{2}-\d{2}", stamp)
    assert text.index(stamp) > text.index("\n---\n")  # after the frontmatter


def test_a_new_release_changes_the_render() -> None:
    """Q1, Q7: the model part follows the pin, so an installed copy becomes stale."""
    assert render(compiled_model("inventory", "1.0.0")) != render(
        compiled_model("inventory", "1.1.0")
    )


# ---- independent completeness check -----------------------------------------------------


def expected_mentions(model: CompiledModel, prefixes: dict[str, str]) -> list[str]:
    """What SKILL.md must name for each entity type, read from the compiled model."""
    found = []
    for curie in sorted(prefixes):
        cls = model.classes[curie]
        found += [curie, format_alias(prefixes[curie], 1)]
        for attr in cls.attributes.values():
            if attr.kind == "enum":
                found += [f"`{v}`" for v in model.enums[attr.type].value_names()]
            if attr.kind == "lifecycle":
                found += [f"`{s}`" for s in model.lifecycles[attr.type].state_names()]
        for name, relation in model.relations.items():
            touches = (relation.domain and model.is_a_any(curie, relation.domain)) or (
                relation.range and model.is_a_any(curie, relation.range)
            )
            if touches:
                found.append(f"`{name}`")
    return found


@pytest.mark.parametrize("ontology", TOY_ONTOLOGIES)
def test_every_entity_type_is_complete(ontology: str) -> None:
    model = compiled_model(ontology)
    prefixes = {str(c): p for c, p in graph_entry(model).alias_prefixes.items()}
    assert prefixes, "positive control: the fixture has entity types"
    files = render(model)
    skill, reference = files[SKILL_FILE].decode(), files[MODEL_FILE].decode()
    missing = [m for m in expected_mentions(model, prefixes) if m not in skill]
    assert missing == []
    assert [c for c in model.classes if f"## `{c}`" not in reference] == []


def test_the_completeness_check_sees_a_gap() -> None:
    """Positive control: a value missing from the render is found."""
    model = compiled_model("inventory")
    prefixes = {str(c): p for c, p in graph_entry(model).alias_prefixes.items()}
    skill = render(model)[SKILL_FILE].decode().replace("`worn`", "`old`")
    assert [m for m in expected_mentions(model, prefixes) if m not in skill] == ["`worn`"]


def test_without_alias_prefixes_every_concrete_type_is_listed() -> None:
    model = compiled_model("notes_and_sources")
    skill = render(model, prefixes=False)[SKILL_FILE].decode()
    rows = re.findall(r"^\| `([a-z]+:[A-Za-z]+)` \|", skill, re.MULTILINE)
    concrete = [c for c, d in sorted(model.classes.items()) if not d.abstract]
    assert rows[: len(concrete)] == concrete
    assert "| `nas:Book` | A published book. Is a `nas:Source`. |" in skill  # its relations apply
    assert "Aliases:" not in skill


def test_lookup_rule_and_label_roles() -> None:
    skill = render(compiled_model("notes_and_sources"))[SKILL_FILE].decode()
    assert "`nas:Topic`: `label` (main name), `synonyms` (other names)" in skill
    assert "exactly one candidate matches exactly" in skill and "ask" in skill
    assert "`NOTE-0001`" in skill and "never `NOTE-1`" in skill
    no_labels = render(compiled_model("inventory", "1.0.0"))[SKILL_FILE].decode()
    assert "No type of this graph has names" in no_labels


