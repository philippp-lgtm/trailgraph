@pytest.mark.parametrize("ontology", TOY_ONTOLOGIES)
def test_fixture_renders_stay_small(ontology: str) -> None:
    files = render(compiled_model(ontology))
    assert files[SKILL_FILE].count(b"\n") < MAX_SKILL_LINES // 4


def test_a_large_model_breaks_the_size_rule() -> None:
    documents, graph = render_inputs(compiled_model("inventory"))
    item = documents["type"]["inv:Item"]
    for n in range(MAX_SKILL_LINES):
        curie = f"inv:Synthetic{n}"
        documents["type"][curie] = {**item, "type": {**item["type"], "curie": curie}}
        documents["types"]["types"].append({"curie": curie, "abstract": False})
        graph["alias_prefixes"][curie] = f"S{n}"
    files, problems = render_checked(template_files(), documents, graph, name=GRAPH_SKILL_NAME)
    assert files is None and {p.rule for p in problems} == {"size"}


def test_renderer_refuses_other_documents() -> None:
    documents, graph = render_inputs(compiled_model("inventory"))
    template, _ = parse_template(template_files())
    assert template is not None
    with pytest.raises(ValueError, match=r"graph_cli\.model/1"):
        render_graph_skill(template, {**documents, "types": {"schema": "x/1"}}, graph)
    del documents["type"]["inv:Item"]
    with pytest.raises(ValueError, match="do not match"):
        render_graph_skill(template, documents, graph)


def test_a_model_with_stored_files_names_the_file_workflow() -> None:
    with_files = render(compiled_model("notes_and_sources", "1.1.0"))[SKILL_FILE].decode()
    assert "`graph file add <file> --graph example_graph --json`" in with_files
    assert "`files:from_file`" in with_files
    without = render(compiled_model("notes_and_sources"))[SKILL_FILE].decode()
    assert "graph file add" not in without
