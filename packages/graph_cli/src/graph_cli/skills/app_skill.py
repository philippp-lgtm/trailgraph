SKILL_NAME: Final = "graph-cli"
GENERATOR: Final = "graph_cli.skills/1"
INVENTORY_SCHEMA: Final = "graph_cli.inventory/1"
SKILL_FILE: Final = "SKILL.md"
COMMANDS_FILE: Final = "references/commands.md"
ERRORS_FILE: Final = "references/errors.md"
BANNER: Final = (
    "<!-- Generated by graph_cli.skills from `graph describe commands --json`."
    " Do not edit; regenerate. -->"
)

DESCRIPTION: Final = (
    "Read and write a typed knowledge graph through its command-line tool: find, inspect"
    " and traverse entities, record new facts, update or correct them and move them through"
    " their lifecycle, all validated against the graph's ontology and audited. Use when the"
    " user asks what is known about something, wants knowledge recorded or changed in a"
    " graph, or wants to explore how things relate. Do not use for creating graphs, changing"
    " ontologies or schemas, migrations, archiving, or editing store files directly."
)

# What to do per error category; an inventory with another category is refused.
CATEGORY_GUIDANCE: Final[Mapping[str, str]] = {
    "invalid": "The input breaks the ontology or a rule. Read `error.details.findings`,"
    " fix the values and retry with `--dry-run` first.",
    "not_found": "The graph, entity or term does not exist. Check the reference;"
    " `error.details` may list close matches.",
    "refused": "The request cannot be carried out as given (an ambiguous reference, a"
    " change set too large or with broken local references, a graph that is archived,"
    " read-only or outside the project). Change the request; do not repeat it.",
    "usage": "The command line is wrong or incomplete (for example no graph selected)."
    " Check the command in `references/commands.md` or `graph describe commands --json`.",
    "denied": "You are not permitted (or the batch exceeds your limit). Stop and tell the"
    " user; do not retry under another identity. If a reason is required, retry with"
    " `--reason`.",
    "conflict": "Someone else changed the data or the key was used for another request."
    " Read the entity again, then decide whether to retry.",
    "unavailable": "Storage, the audit log, a lock or the installation is not usable. If"
    " `error.retryable` is true, retry later with the same `--idempotency-key`; otherwise"
    " tell the user, a maintainer has to look at it.",
    "internal": "A bug in the CLI. Report the full envelope to the user.",
}

SKILL_BODY: Final = """\
# graph CLI

`graph` reads and writes knowledge graphs. Every graph has an ontology that
fixes its types, fields, relations and lifecycles; every write is validated
against it and audited. The CLI is on `PATH`.

## Ground rules

- Pass `--json` to every command and read the envelope (below), not the text.
- The live CLI wins. If this skill and `graph describe commands --json` or
  `--help` disagree, trust the CLI.
- If a skill for the selected graph exists, read it first: it names the
  graph's types, fields and relations. This skill never does.
- Never guess a type, field, relation or state name. Ask `graph describe`.
- Reads never change anything. Writes are recorded with who made them.
- `graph skills` commands install agent skills such as this one. Run them
  only when the user asks; `graph skills check` only reads and is safe.

## Workflow

1. Pick a graph: `graph graphs --json` lists the graphs you may use. Select
   one with `--graph <graph>` on every command (a project may preset a
   default).
2. Learn the model: `graph describe types --json`, then
   `graph describe type <type> --json` for fields, relations and lifecycles.
3. Read: `graph find --type <type> --where <attr>=<value> --json`,
   `graph get <id> --json`, `graph neighbors <id> --json`. Follow
   `page.next_offset` or the hint when `page.truncated` is true. To find
   something by name, `graph lookup <value> --json` lists candidates, since
   names are not unique. Use the returned id only when exactly one
   candidate matches exactly (`match.kind` is `exact`). With several
   candidates, or only prefix matches, do not answer about one of them
   first: list them and ask which one is meant, then answer.
4. Preview every write with `--dry-run --json` and check the findings.
5. Write with the same command without `--dry-run`.
6. Verify with `graph get <id> --json`.

## Writing safely

- Pass `--idempotency-key` with a key of your choice; retrying with the same
  key never writes twice.
- Pass `--expect` with the `rev` you read so that a concurrent change is a
  conflict instead of a lost update. `graph get` shows it as
  `data.entity.rev`; a write returns the new one in `data.entities[].rev`.
- Give `--reason` when the change needs one; some operations require it.
- Nothing is deleted. Correct with `graph supersede` (a newer entity
  replaces older ones) or `graph retract` (withdrawn); state changes go
  through `graph transition`.
- Prefer the single-operation commands. `graph apply` takes change set
  documents for batches: write the document to a file, dry-run it with
  `graph apply <file> --dry-run --json`, then apply it. Its idempotency key
  is `idempotency_key` in the document, or `--idempotency-key` for a file
  with a single document.
- `graph whoami --json` shows who you act as and what you may do.

## Files

Graphs whose ontology imports the `files` module store files: scans,
documents, saved web pages.

- When facts come from a file, store the file first:
  `graph file add <file> --json`. Known content is not stored twice; the
  result then names the file that holds it.
- Link every entity you take from the file to it, with the page:
  `graph link <id> files:from_file <id> --qualifier-json page=<value> --json`
  (`last_page` for a range, `--qualifier locator=<value>` for a place that
  is not a page).
- Read a stored file at the path from `graph file path <id> --json`. Never
  edit, move or delete anything there.
- `graph` does not read files; you do. Do not guess what you cannot read:
  leave the field out and tell the user.
- `graph file check --json` compares stored files with where they came
  from. On `changed`, store the new version with `graph file add` and
  replace the old file: `graph supersede <id> <id> --reason <value>`.

## Output envelope

Every `--json` call prints one JSON object on stdout.

- Keys, always present: {envelope_keys}.
- `ok` tells success; `data` holds the result, `page` the paging of lists.
- Read the whole object; cutting it with `head` or similar loses fields
  such as `rev`.
- On failure `error` holds {error_keys}. `hint` is a command to run next,
  or null.
- Warnings never change the exit code.

## Commands

{commands_table}

Global options, before or after the command (`graph --graph <graph> find`
equals `graph find --graph <graph>`):

{global_table}

## Exit codes

{exit_table}

## References

- [references/commands.md](references/commands.md): arguments, options,
  limits and examples of every command.
- [references/errors.md](references/errors.md): every error code and what to
  do per category.
"""

# B9.2 and B9.8; the docs-vs-code test compares them with the envelope renderer.
ENVELOPE_KEYS: Final = (
    "schema",
    "ok",
    "command",
    "graph",
    "data",
    "page",
    "hints",
    "warnings",
    "error",
)
ERROR_KEYS: Final = ("code", "category", "retryable", "message", "hint", "details")


def render_app_skill(inventory: Mapping[str, JsonValue]) -> dict[str, str]:
    """``{relative path: content}`` of ``skills/graph-cli/``; refuses what it cannot render."""
    doc, commands, codes = _ordered(inventory)
    return {
        SKILL_FILE: _skill(doc, commands, codes),
        COMMANDS_FILE: _commands_file(commands),
        ERRORS_FILE: _errors_file(codes),
    }


def inventory_hash(inventory: Mapping[str, JsonValue]) -> str:
    """``metadata.inventory_hash`` of the rendered skill: C.1 hash, commands and codes sorted."""
    return hash_value(_ordered(inventory)[0])


def _ordered(
    inventory: Mapping[str, JsonValue],
) -> tuple[JsonObject, list[JsonObject], list[JsonObject]]:
    doc = _checked(inventory)
    commands = sorted(
        (as_object(c, "commands[]") for c in req_list(doc, "commands")),
        key=lambda c: [str(p) for p in as_list(c["path"], "path")],
    )
    codes = sorted(
        (as_object(e, "error_codes[]") for e in req_list(doc, "error_codes")),
        key=lambda e: req_str(e, "code"),
    )
    doc = {**doc, "commands": list(commands), "error_codes": list(codes)}  # stamp order-free
    return doc, commands, codes


def _checked(inventory: Mapping[str, JsonValue]) -> JsonObject:
    doc = as_object(dict(inventory), "inventory")
    if doc.get("schema") != INVENTORY_SCHEMA:
        raise ValueError(f"expected {INVENTORY_SCHEMA}, got {doc.get('schema')!r}")
    if doc.get("surface") != "app":
        raise ValueError(f"skill 1 renders the app surface, got {doc.get('surface')!r}")
    if not req_list(doc, "commands"):
        raise ValueError("the inventory lists no commands (truncated?)")
    for entry in req_list(doc, "error_codes"):
        category = req_str(as_object(entry, "error_codes[]"), "category")
        if category not in CATEGORY_GUIDANCE:
            raise ValueError(f"no guidance for error category {category!r}")
    return doc


def _skill(doc: JsonObject, commands: Sequence[JsonObject], codes: Sequence[JsonObject]) -> str:
    metadata = {
        "generator": GENERATOR,
        "inventory_hash": hash_value(doc),
        "inventory_schema": req_str(doc, "schema"),
        "program": req_str(doc, "program"),
        "program_version": req_str(doc, "program_version"),
    }
    front = ["---", f"name: {SKILL_NAME}", f"description: {_quoted(DESCRIPTION)}", "metadata:"]
    front += [f"  {key}: {_quoted(value)}" for key, value in metadata.items()]
    front.append("---")
    body = SKILL_BODY.format(
        envelope_keys=_series(ENVELOPE_KEYS),
        error_keys=_series(ERROR_KEYS),
        commands_table="\n".join(
            table(
                ["Command", "Kind", "Summary"],
                [
                    [code(_command_line(c)), cell(req_str(c, "kind")), cell(req_str(c, "summary"))]
                    for c in commands
                ],
            )
        ),
        global_table="\n".join(
            table(
                ["Option", "Type", "Summary"],
                [
                    [
                        code(req_str(o, "name")),
                        cell(req_str(o, "type")),
                        cell(req_str(o, "summary")),
                    ]
                    for o in _objects(doc, "global_options")
                ],
            )
        ),
        exit_table="\n".join(table(["Exit", "Categories"], _exit_rows(codes))),
    )
    return "\n".join([*front, "", BANNER, "", body])


def _commands_file(commands: Sequence[JsonObject]) -> str:
    lines = [
        BANNER,
        "",
        "# Commands",
        "",
        "Every command accepts `--json`. Per-command error codes:"
        " `graph describe commands --json`.",
    ]
    for command in commands:
        lines += ["", f"## {_command_line(command)}", "", cell(req_str(command, "summary")), ""]
        action = command.get("action")
        lines.append(
            f"Kind: {req_str(command, 'kind')}. Surface: {req_str(command, 'surface')}."
            f" Action: {code(str(action)) if action is not None else 'none'}."
            f" Exit codes: {', '.join(str(e) for e in as_list(command['exit_codes'], 'exit'))}."
        )
        lines += ["", "Usage: " + code(_usage(command))]
        for key, title in (("args", "Argument"), ("options", "Option")):
            params = _objects(command, key)
            if params:
                lines += [
                    "",
                    *table(
                        [title, "Type", "Required", "Repeatable", "Summary"],
                        [
                            [
                                code(req_str(p, "name")),
                                cell(req_str(p, "type")),
                                _yes(p["required"]),
                                _yes(p["repeatable"]),
                                cell(req_str(p, "summary")),
                            ]
                            for p in params
                        ],
                    ),
                ]
        limits = req_obj(command, "limits")
        if limits:
            lines += [
                "",
                *table(
                    ["Limit", "Value"],
                    [[code(name), cell(str(limits[name]))] for name in sorted(limits)],
                ),
            ]
        lines += [
            "",
            *table(
                ["Example", "Summary"],
                [
                    [code(req_str(e, "command")), cell(req_str(e, "summary"))]
                    for e in _objects(command, "examples")
                ],
            ),
        ]
    return "\n".join(lines) + "\n"


def _errors_file(codes: Sequence[JsonObject]) -> str:
    categories = sorted(
        {req_str(e, "category") for e in codes}, key=lambda c: (_exit_of(codes, c), c)
    )
    lines = [
        BANNER,
        "",
        "# Error codes",
        "",
        "Every failure has a `code` and a `category`; the exit code depends on the category"
        " only. `error.retryable` tells whether the same call may succeed later.",
        "",
        "## What to do",
        "",
        *table(
            ["Error category", "Exit", "What to do"],
            [[code(c), str(_exit_of(codes, c)), CATEGORY_GUIDANCE[c]] for c in categories],
        ),
        "",
        "## Codes",
        "",
        *table(
            ["Error code", "Error category", "Exit"],
            [
                [code(req_str(e, "code")), cell(req_str(e, "category")), str(req_int(e, "exit"))]
                for e in codes
            ],
        ),
    ]
    return "\n".join(lines) + "\n"


def _command_line(command: JsonObject) -> str:
    return " ".join(["graph", *(str(p) for p in as_list(command["path"], "path"))])


def _usage(command: JsonObject) -> str:
    parts = [_command_line(command)]
    for arg in _objects(command, "args"):
        name = req_str(arg, "name").upper()
        name = f"{name}..." if arg["repeatable"] else name
        parts.append(name if arg["required"] else f"[{name}]")
    if _objects(command, "options"):
        parts.append("[OPTIONS]")
    return " ".join(parts)


def _exit_rows(codes: Sequence[JsonObject]) -> list[list[str]]:
    by_exit: dict[int, set[str]] = {0: {"ok"}}
    for entry in codes:
        by_exit.setdefault(req_int(entry, "exit"), set()).add(req_str(entry, "category"))
    return [
        [str(exit_code), ", ".join(code(c) for c in sorted(by_exit[exit_code]))]
        for exit_code in sorted(by_exit)
    ]


def _exit_of(codes: Sequence[JsonObject], category: str) -> int:
    (exit_code,) = {req_int(e, "exit") for e in codes if e["category"] == category}
    return exit_code


def _objects(doc: JsonObject, key: str) -> list[JsonObject]:
    return [as_object(item, f"{key}[]") for item in req_list(doc, key)]


def _yes(value: JsonValue) -> str:
    return "yes" if value is True else "no"


def _series(names: Sequence[str]) -> str:
    return ", ".join(f"`{name}`" for name in names)


def _quoted(text: str) -> str:
    """A YAML double-quoted scalar (JSON string syntax is valid YAML)."""
    if any(ord(ch) < 0x20 or ord(ch) > 0x7E for ch in text):
        raise ValueError(f"frontmatter values are printable ASCII: {text!r}")
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'
